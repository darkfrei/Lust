-- the buttons work: Play opens the game, clicks count, escape returns, options change the step
local function click(x, y)
  mouse(x, y, false) step()
  mouse(x, y, true) press('mouse') step()
  mouse(x, y, false) step()
end

step()
assert(get('app', 'screen') == 0, 'starts at the menu')
click(400, 240)
assert(get('app', 'screen') == 1, 'Play opens the game: ' .. get('app', 'screen'))
click(400, 300) click(400, 300) click(400, 300)
assert(get('app', 'score') == 3, 'three clicks: ' .. get('app', 'score'))
click(5, 5)
assert(get('app', 'score') == 3, 'a click beside a button counts nothing')
press('escape') step()
assert(get('app', 'screen') == 0, 'escape goes back')
press('down') step() press('enter') step()
assert(get('app', 'screen') == 2, 'down and enter open Options: ' .. get('app', 'screen'))
click(400, 260)
assert(get('app', 'fast') == 1, 'the toggle')
click(50, 40)
assert(get('app', 'screen') == 0, 'the Menu button goes back')
assert(draw():find_plain('My Game'), 'the title is drawn')
-- a world started again loads the save: the score is kept (the test keeps saves in memory)
set('app', 'score', 0) set('app', 'loaded', 0) step()
assert(get('app', 'score') == 3, 'the save was loaded: ' .. get('app', 'score'))
