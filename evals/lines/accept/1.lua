step(2)
assert(get('app', 'screen') == 0, 'starts at the menu')
local f = draw()
assert(f:find_plain('Lines'), 'the title Lines is drawn')
assert(f:find_plain('Играть') and f:find_plain('Выход'), 'both buttons are drawn')
assert(f:find_plain('circle'), 'the row of circles is drawn')
press('enter') step(3)
assert(get('app', 'screen') == 1, 'enter starts the game screen')
press('escape') step(3)
assert(get('app', 'screen') == 0, 'escape goes back to the menu')
assert(#events() == 0, 'no quit yet')
press('down') step(2) press('enter') step(3)
local e = events()
assert(e[1] == 'quit', 'down and enter choose Exit: the game asks to quit')
